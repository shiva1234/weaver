package com.weaver.weaver_api.service;

import com.weaver.weaver_api.model.Category;
import com.weaver.weaver_api.repository.CategoryRepository;
import com.weaver.weaver_api.web.NotFoundException;
import jakarta.transaction.Transactional;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.UUID;

@Service
@RequiredArgsConstructor
@Transactional
public class CategoryService {

    private final CategoryRepository categories;

    @Transactional(Transactional.TxType.SUPPORTS)
    public List<Category> listAll() {
        return categories.findAll();
    }

    @Transactional(Transactional.TxType.SUPPORTS)
    public Category getOne(UUID id) {
        return categories.findById(id)
                .orElseThrow(() -> new NotFoundException("Category id " + id + " not found"));
    }

    public Category create(Category body) {
        // Do NOT set id; it’s generated by JPA
        // Copy only fields you allow from the body (example: name, slug, active)
        Category c = new Category();
        c.setName(body.getName());
        // if you have slug/active/etc., set them here:
        // c.setSlug(body.getSlug());
        // c.setActive(body.getActive());
        return categories.save(c);
    }

    public Category update(UUID id, Category body) {
        Category c = categories.findById(id)
                .orElseThrow(() -> new NotFoundException("Category id " + id + " not found"));

        // Update only allowed mutable fields
        c.setName(body.getName());
        // if present in your entity:
        // c.setSlug(body.getSlug());
        // c.setActive(body.getActive());

        return categories.save(c);
    }

    public void delete(UUID id) {
        if (!categories.existsById(id)) {
            throw new NotFoundException("Category id " + id + " not found");
        }
        categories.deleteById(id);
    }
}